interface TrackSeed {
  n: number;
  artistId: string;
  albumId: string | null;
  title: string;
  slug: string;
  description: string;
  genreId: string;
  moodIds: string[];
  languageCode: string;
  countryCode: string;
  productionType: 'fully_ai' | 'ai_assisted';
  aiTools: string;
  visibility: 'public' | 'unlisted' | 'private';
  reviewStatus: Track['reviewStatus'];
  publishStatus: Track['publishStatus'];
  releaseAt: string;
  durationMs: number;
  lyrics: string;
  credits: string;
  accent: string;
  audioIndex: number;
  qualifiedPlays: number;
  likeCount: number;
}

function buildTrack(seed: TrackSeed): Track {
  return {
    id: ID.track(seed.n),
    artistId: seed.artistId,
    albumId: seed.albumId,
    title: seed.title,
    slug: seed.slug,
    description: seed.description,
    genreId: seed.genreId,
    moodIds: seed.moodIds,
    languageCode: seed.languageCode,
    countryCode: seed.countryCode,
    productionType: seed.productionType,
    aiTools: seed.aiTools,
    explicit: false,
    visibility: seed.visibility,
    reviewStatus: seed.reviewStatus,
    publishStatus: seed.publishStatus,
    releaseAt: seed.releaseAt,
    durationMs: seed.durationMs,
    lyrics: seed.lyrics,
    credits: seed.credits,
    artwork: { url: '', accent: seed.accent },
    audioUrl: '',
    audio: {
      kind: 'rendition',
      objectKey: `seed-audio/track-${seed.audioIndex}.mp3`,
      format: 'mp3',
      bitrateKbps: 320,
      sampleRate: 44100,
      channels: 2,
      bytes: 0,
      sha256: `seed-track-${seed.audioIndex}`,
      processingStatus: 'ready',
    },
    qualityLabel: 'high',
    qualifiedPlays: seed.qualifiedPlays,
    likeCount: seed.likeCount,
    commentCount: 0,
    createdAt: seed.releaseAt,
    updatedAt: seed.releaseAt,
  };
}

